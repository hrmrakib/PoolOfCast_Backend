    # ---------- book ----------

    def test_book_success_creates_bookings_and_autoshortlists(self):
        resp = self._post_json(
            "/api/v1/talents/book",
            {
                "job_id": self.job.job_id,
                "talent_id": self.talent.talent_id,
                "booking_dates": [self.available_date_1.isoformat(), self.available_date_2.isoformat()],
            },
        )
        body = resp.json()
        print("BOOK ->", resp.status_code, body)
        self.assertEqual(resp.status_code, 200)
        self.assertIn("booked successfully", body["status_message"])

        self.assertEqual(
            Booking.objects.filter(user_id=self.owner_user.user_id, talent=self.talent).count(), 2
        )
        self.job.refresh_from_db()
        self.assertEqual(self.job.shortlisted_count, 1)
        self.assertTrue(
            ShortListedTalent.objects.filter(user_id=self.owner_user.user_id, talent=self.talent, job=self.job).exists()
        )

        self.assertFalse(
            TalentAvailableDate.objects.filter(
                talent=self.talent, available_date=self.available_date_1, is_active=True
            ).exists()
        )

        self.assertEqual(len(mail.outbox), 1)

    def test_book_includes_role_text_when_assigned(self):
        role = JobRole.objects.create(job=self.job, job_role="Lead", talent=self.talent)
        JobRoleAssignment.objects.create(job_id=int(self.job.job_id), job_role=role, talent=self.talent)

        resp = self._post_json(
            "/api/v1/talents/book",
            {
                "job_id": self.job.job_id,
                "talent_id": self.talent.talent_id,
                "booking_dates": [self.available_date_1.isoformat()],
            },
        )
        body = resp.json()
        print("BOOK(with role) ->", resp.status_code, body)
        self.assertEqual(resp.status_code, 200)
        self.assertIn("as Lead", body["status_message"])
        self.assertIn("(Lead)", mail.outbox[0].subject)


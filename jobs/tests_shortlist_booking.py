    # ---------- delete-shortlist ----------

    def test_delete_shortlist_by_job_id(self):
        self._post_json(
            "/api/v1/talents/shortlist", {"job_id": self.job.job_id, "talent_id": self.talent.talent_id}
        )
        resp = self.client.delete(
            f"/api/v1/talents/delete-shortlist?talent_id={self.talent.talent_id}&job_id={self.job.job_id}",
            **self.owner_auth_header,
        )
        body = resp.json()
        print("DELETE SHORTLIST(job) ->", resp.status_code, body)
        self.assertEqual(resp.status_code, 200)

        self.job.refresh_from_db()
        self.assertEqual(self.job.shortlisted_count, 0)
        self.assertFalse(
            ShortListedTalent.objects.filter(user_id=self.owner_user.user_id, talent=self.talent).exists()
        )


    def test_book_conflicting_date_returns_400(self):
        self._post_json(
            "/api/v1/talents/book",
            {
                "job_id": self.job.job_id,
                "talent_id": self.talent.talent_id,
                "booking_dates": [self.available_date_1.isoformat()],
            },
        )
        TalentAvailableDate.objects.filter(
            talent=self.talent, available_date=self.available_date_1
        ).update(is_active=True)
        resp = self._post_json(
            "/api/v1/talents/book",
            {
                "job_id": self.job.job_id,
                "talent_id": self.talent.talent_id,
                "booking_dates": [self.available_date_1.isoformat()],
            },
        )
        body = resp.json()
        print("BOOK(conflict) ->", resp.status_code, body)
        self.assertEqual(resp.status_code, 400)
        self.assertIn("already booked", body["status_message"])


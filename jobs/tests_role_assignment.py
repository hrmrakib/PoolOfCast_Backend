    # ---------- unassign-role ----------

    def test_unassign_role_missing_params_returns_400(self):
        resp = self.client.patch("/api/v1/jobs/unassign-role", **self.owner_auth_header)
        self.assertEqual(resp.status_code, 400)

    def test_unassign_role_requires_auth(self):
        role = JobRole.objects.create(job=self.job, job_role="Lead", talent=self.talent_a)
        resp = self.client.patch(f"/api/v1/jobs/unassign-role?job_role_id={role.id}")
        self.assertEqual(resp.status_code, 401)

    def test_unassign_role_rejects_non_owner(self):
        role = JobRole.objects.create(job=self.job, job_role="Lead", talent=self.talent_a)
        resp = self.client.patch(
            f"/api/v1/jobs/unassign-role?job_role_id={role.id}", **self.other_auth_header
        )
        print("UNASSIGN (non-owner) ->", resp.status_code, resp.json())
        self.assertEqual(resp.status_code, 403)

    def test_unassign_role_by_job_role_id_clears_canonical_row(self):
        role = JobRole.objects.create(job=self.job, job_role="Lead", talent=self.talent_a)
        JobRoleAssignment.objects.create(job_id=int(self.job.job_id), job_role=role, talent=self.talent_a)

        resp = self.client.patch(
            f"/api/v1/jobs/unassign-role?job_role_id={role.id}", **self.owner_auth_header
        )
        body = resp.json()
        print("UNASSIGN (by role id) ->", resp.status_code, body)
        self.assertEqual(resp.status_code, 200)

        role.refresh_from_db()
        self.assertIsNone(role.talent_id)
        self.assertFalse(role.assign_status)
        self.assertFalse(JobRoleAssignment.objects.filter(job_role_id=role.id).exists())

    def test_unassign_role_falls_back_to_remaining_assignment(self):
        role = JobRole.objects.create(job=self.job, job_role="Lead", talent=self.talent_a)
        JobRoleAssignment.objects.create(job_id=int(self.job.job_id), job_role=role, talent=self.talent_a)
        JobRoleAssignment.objects.create(job_id=int(self.job.job_id), job_role=role, talent=self.talent_b)

        resp = self.client.patch(
            f"/api/v1/jobs/unassign-role?job_role_id={role.id}", **self.owner_auth_header
        )
        print("UNASSIGN (fallback remaining) ->", resp.status_code, resp.json())
        self.assertEqual(resp.status_code, 200)

        role.refresh_from_db()
        self.assertEqual(role.talent_id, self.talent_b.talent_id)
        self.assertTrue(role.assign_status)

    def test_unassign_role_by_job_id_single_assigned_role(self):
        role = JobRole.objects.create(job=self.job, job_role="Lead", talent=self.talent_a)
        JobRole.objects.create(job=self.job, job_role="Supporting", talent=None)
        JobRoleAssignment.objects.create(job_id=int(self.job.job_id), job_role=role, talent=self.talent_a)

        resp = self.client.delete(
            f"/api/v1/jobs/unassign-role?job_id={self.job.job_id}", **self.owner_auth_header
        )
        print("UNASSIGN (by job_id, delete method) ->", resp.status_code, resp.json())
        self.assertEqual(resp.status_code, 200)

        role.refresh_from_db()
        self.assertIsNone(role.talent_id)

    def test_unassign_role_by_job_id_multiple_assigned_roles_returns_400(self):
        role1 = JobRole.objects.create(job=self.job, job_role="Lead", talent=self.talent_a)
        role2 = JobRole.objects.create(job=self.job, job_role="Supporting", talent=self.talent_b)

        resp = self.client.patch(
            f"/api/v1/jobs/unassign-role?job_id={self.job.job_id}", **self.owner_auth_header
        )
        self.assertEqual(resp.status_code, 400)

    def test_unassign_role_by_job_id_no_assigned_roles_returns_404(self):
        JobRole.objects.create(job=self.job, job_role="Lead", talent=None)
        resp = self.client.patch(
            f"/api/v1/jobs/unassign-role?job_id={self.job.job_id}", **self.owner_auth_header
        )
        self.assertEqual(resp.status_code, 404)

    def test_unassign_role_null_target_falls_back_to_sibling_row(self):
        empty_role = JobRole.objects.create(job=self.job, job_role="Lead", talent=None)
        assigned_role = JobRole.objects.create(job=self.job, job_role="Lead", talent=self.talent_a)
        JobRoleAssignment.objects.create(
            job_id=int(self.job.job_id), job_role=empty_role, talent=self.talent_a
        )

        resp = self.client.patch(
            f"/api/v1/jobs/unassign-role?job_role_id={empty_role.id}", **self.owner_auth_header
        )
        print("UNASSIGN (null target, sibling fallback) ->", resp.status_code, resp.json())
        self.assertEqual(resp.status_code, 200)

        empty_role.refresh_from_db()
        self.assertIsNone(empty_role.talent_id)  # untouched - spec only updates target_role when it held the talent
        self.assertFalse(
            JobRoleAssignment.objects.filter(job_role_id=empty_role.id, talent_id=self.talent_a.talent_id).exists()
        )
